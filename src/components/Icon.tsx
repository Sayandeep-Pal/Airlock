/** Where a result was produced: on this device (filled) or in the cloud (outlined). */
export function WhereBadge({ where, children }: { where: 'on_device' | 'in_cloud'; children: React.ReactNode }) {
  return (
    <span className={`badge ${where}`}>
      <Icon name={where === 'on_device' ? 'device' : 'cloud'} size={13} />
      {children}
    </span>
  );
}

/** Text with [TYPE_N] placeholders rendered as chips. */
export function TokenText({ text }: { text: string }) {
  const parts = text.split(/(\[[A-Z]+_\d+\])/g);
  return <>{parts.map((p, i) => (i % 2 ? <span key={i} className="tok">{p}</span> : p))}</>;
}
